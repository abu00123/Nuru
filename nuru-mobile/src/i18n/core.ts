export function translate(text: string, language: Language): string { return catalogs[language]?.[text] ?? text; }
export function validLanguage(value: unknown): value is Language { return languages.some(l => l.code === value); }
export type ArticleTranslations = Partial<Record<Language, {title: string; summary: string; content: string; reviewed?: boolean}>>;
export function localizeArticle<T extends {title: string; summary: string; content: string; translations?: ArticleTranslations}>(entry:T, language:Language): T & {translationFallback: boolean} {
  const translated = entry.translations?.[language];
  const complete = language !== 'en' && translated?.reviewed === true && ['title','summary','content'].every(key => typeof translated[key as 'title'] === 'string' && translated[key as 'title'].trim());
  return {...entry, ...(complete ? {title: translated!.title,summary: translated!.summary,content: translated!.content} : {}), translationFallback: language !== 'en' && !complete};
}
